"""生成各目录 README 里的文件索引（暂无契约 ID：仓库导航）。只读 git 暂存区与提交历史，标准库，Mac 自带 python3 可跑。

方案见 docs/adr/00004-personal-research-repo-layout.md 决定第 7 条：不搬文件，靠索引让人找得到东西。
每份 README 里两行标记之间的内容由本脚本生成，标记外的文字手写；没有标记的 README 在末尾追加。
文件内容取暂存区的 blob（git ls-files -s），所以工作区里没 add 的改动（例如那 92 个未提交的 results 文件）不会进索引；
新文件要先 git add 再跑。日期取最后一次改动它的提交（%cs），还没提交的写「未提交」。
分组只按文件名规则，规则写在 GROUPS 里，分不准的落「其他」。★ 表示工程手册中文版提到过这个文件名。

README 一律英文（rxzhou 11/06）：表头、分组名、说明句都是英文；文件头里的中文用途说明按路径查 tools/repo_index.en.tsv
（路径<TAB>英文），查不到就留空，不把中文写进 README。加新文件后用 --dump-zh 列出缺译文的条目，补进 tsv。

用法（仓库根）：python3 tools/repo_index.py          写回各 README
              python3 tools/repo_index.py --check  只比较，有过期的索引时退出码 1
              python3 tools/repo_index.py --dump-zh  列出用途说明是中文、tsv 里还没有译文的条目（路径<TAB>中文）
"""
import ast
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

BEGIN = "<!-- index start: generated by tools/repo_index.py, do not edit by hand -->"
END = "<!-- index end -->"
OLD_MARKERS = [("<!-- 索引开始：tools/repo_index.py 生成，不要手改 -->", "<!-- 索引结束 -->")]
TRANSLATIONS = "tools/repo_index.en.tsv"
CJK = re.compile(r"[\u3000-\u303f\u4e00-\u9fff\uff00-\uffef]")
HANDBOOK = "docs/engineering/v2d-track2-engineering-handbook.zh.md"
CODE_SUFFIX = (".py", ".sh")

# 按文件名（去掉 test_ 前缀后）依次匹配，先中先得
