def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def staged_blobs():
    out = {}
    for line in git("ls-files", "-s").splitlines():
        meta, path = line.split("\t", 1)
        out[path] = meta.split()[1]
    return out


def read_blobs(shas):
    """一次 cat-file --batch 读完所有要的 blob，返回 sha → 文本（按 utf-8，坏字节替换）。"""
    uniq = sorted(set(shas))
    p = subprocess.run(["git", "cat-file", "--batch"], input=("\n".join(uniq) + "\n").encode(),
                       capture_output=True, check=True)
    data, pos, out = p.stdout, 0, {}
    for sha in uniq:
        nl = data.index(b"\n", pos)
        size = int(data[pos:nl].split()[2])
        out[sha] = data[nl + 1:nl + 1 + size].decode("utf-8", "replace")
        pos = nl + 1 + size + 1
    return out


def last_dates():
    """一遍 git log：路径 → (最后改动日期, 最早出现日期)。"""
    last, first, day = {}, {}, None
    for line in git("log", "--format=%x00%cs", "--name-only", "HEAD").splitlines():
        if line.startswith("\0"):
            day = line[1:]
        elif line:
            last.setdefault(line, day)
            first[line] = day
    return last, first


def short(s, n=70):
    s = " ".join(s.split()).replace("|", "\\|")
    return s if len(s) <= n else s[:n - 1] + "…"


def purpose(path, text, n=70):
    if path.endswith(".py"):
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            m = re.match(r'\s*(?:"""|\'\'\')(.*?)(?:"""|\'\'\'|\n)', text, re.S)
            doc = m.group(1) if m else ""
        first = doc.strip().splitlines()[0] if doc.strip() else ""
    elif path.endswith(".sh") or text.startswith("#!"):
        first = ""
        for line in text.splitlines()[:15]:
            if line.startswith("#!"):
                continue
            if line.startswith("#"):
                first = line.lstrip("#").strip()
                if first:
                    break
            elif line.strip():
                break
    elif path.endswith(".md"):
        m = re.search(r"^#\s+(.+)$", text, re.M)
        first = m.group(1) if m else ""
    else:
        first = ""
        for line in text.splitlines()[:15]:
            if line.startswith("#") and line.lstrip("#").strip():
                first = line.lstrip("#").strip()
                break
    return short(first, n)


def group_of(name):
    base = name[5:] if name.startswith("test_") else name
    for label, rx in GROUPS:
        if re.match(rx, base):
            return label
    return "Other"


def table(rows, head):
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


class Repo:
    def __init__(self):
        self.blobs = staged_blobs()
        self.last, self.first = last_dates()
        self.handbook = set(re.findall(r"[A-Za-z0-9_.-]+\.(?:py|sh)", Path(HANDBOOK).read_text("utf-8")))
        want = [s for p, s in self.blobs.items()
                if p.endswith(CODE_SUFFIX + (".md",)) or p.startswith(("results/", "stages/policy/queues/"))
                or "." not in p.rsplit("/", 1)[-1]]
        self.text = read_blobs(want)
        self.en = {}
        if Path(TRANSLATIONS).exists():
            for line in Path(TRANSLATIONS).read_text("utf-8").splitlines():
                if "\t" in line and not line.startswith("#"):
                    k, v = line.split("\t", 1)
                    self.en[k] = v.strip()
        self.missing = {}

    def content(self, path):
        return self.text.get(self.blobs.get(path, ""), "")

    def date(self, path):
        return self.last.get(path, "uncommitted")

    def describe(self, path):
        """文件头的用途说明；中文的换成 tsv 里的英文，没有译文就留空并记进 missing。"""
        raw = purpose(path, self.content(path))
        if not CJK.search(raw):
            return raw
        if path in self.en:
            return short(self.en[path])
        self.missing[path] = purpose(path, self.content(path), 600)
        return ""

    def files(self, d, recursive=False):
        pre = d.rstrip("/") + "/"
        out = [p for p in self.blobs if p.startswith(pre)]
        return sorted(out if recursive else [p for p in out if "/" not in p[len(pre):]])


def code_index(repo, d, link_base=""):
    """一个代码目录：直接放在目录里的脚本按功能分组，测试单列，子目录给一行概况。"""
    files = repo.files(d)
    code = [p for p in files if p.endswith(CODE_SUFFIX) or repo.content(p).startswith("#!")]
    other = [p for p in files if p not in code and not p.endswith("README.md")]
    groups = defaultdict(list)
    tests = []
    for p in code:
        name = p.rsplit("/", 1)[1]
        (tests if name.startswith("test_") else groups[group_of(name) if len(code) > 20 else "Scripts"]).append(p)
    out = [f"`{d}/` holds {len(code)} scripts directly ({len(tests)} of them tests). "
           + ("Groups follow file-name rules. " if len(code) > 20 else "")
           + "Files that the engineering handbook mentions (★) come first, the rest by last change, newest first."]
    order = [g for g, _ in GROUPS] + ["Other", "Scripts"]
    for g in order:
        ps = groups.get(g)
        if not ps:
            continue
        ps.sort(key=lambda p: repo.date(p), reverse=True)
        ps.sort(key=lambda p: p.rsplit("/", 1)[1] not in repo.handbook)
        rows = []
        for p in ps:
            name = p.rsplit("/", 1)[1]
            star = "★ " if name in repo.handbook else ""
            rows.append([f"{star}[`{name}`]({link_base}{name})", repo.describe(p), repo.date(p)])
        out.append(f"\n### {g} ({len(ps)})\n\n" + table(rows, ["File", "Purpose (from the file header)", "Last change"]))
    if tests:
        rows = [[f"[`{p.rsplit('/', 1)[1]}`]({link_base}{p.rsplit('/', 1)[1]})",
                 repo.describe(p), repo.date(p)] for p in sorted(tests)]
        out.append(f"\n### Tests ({len(tests)})\n\n" + table(rows, ["File", "What it checks", "Last change"]))
    if other:
        rows = [[f"[`{p.rsplit('/', 1)[1]}`]({link_base}{p.rsplit('/', 1)[1]})", repo.date(p)] for p in other]
        out.append(f"\n### Configuration and data files ({len(other)})\n\n" + table(rows, ["File", "Last change"]))
    subs = sorted({p[len(d) + 1:].split("/")[0] for p in repo.files(d, True) if "/" in p[len(d) + 1:]})
    if subs:
        rows = []
        for s in subs:
            ps = [p for p in repo.files(f"{d}/{s}", True) if not p.endswith("README.md")]
            ds = sorted(repo.date(p) for p in ps)
            rows.append([f"[`{s}/`]({link_base}{s}/)", str(len(ps)), f"{ds[0]} – {ds[-1]}"])
        out.append(f"\n### Subdirectories ({len(subs)})\n\n" + table(rows, ["Directory", "Files", "Changed"]))
    return "\n".join(out)


def queues_index(repo, d):
    """同一条链的 run 列表、冒烟列表、期望配置合成一行。"""
    files = [p for p in repo.files(d) if not p.endswith("README.md")]
    chains = defaultdict(list)
    for p in files:
        name = p.rsplit("/", 1)[1]
        chains[re.sub(r"(\.expect\.tsv|_smoke\.txt|\.txt|\.ft\.sh|\.sh)$", "", name)].append(p)
    label = {"mf": "mf4090", "ml": "ml40", "l": "l40n", "diag_ml": "ml40 diagnostics"}
    by_host = defaultdict(list)
    for key in chains:
        host = re.match(r"^(diag_ml|mf|ml|l)", key)
        by_host[host.group(1) if host else "Other"].append(key)
    kind = [("_smoke.txt", "smoke"), (".expect.tsv", "expected config"), (".ft.sh", "script"), (".sh", "script"),
            (".txt", "run list")]
    out = [f"{len(files)} files, merged into {len(chains)} chains. The file-name prefix is the host. The run list holds "
           "the full training runs, smoke holds the short runs that go first, and expected config is the positive "
           "configuration that `precheck_expect.sh` checks. Grouped by host, newest change first."]
    for h in ("mf", "ml", "l", "diag_ml", "Other"):
        keys = sorted(by_host.get(h, []), key=lambda k: max(repo.date(p) for p in chains[k]), reverse=True)
        if not keys:
            continue
        rows = []
        for k in keys:
            ps = sorted(chains[k])
            links = []
            for p in ps:
                n = p.rsplit("/", 1)[1]
                tag = next(t for suf, t in kind if n.endswith(suf)) if n.endswith((".txt", ".tsv", ".sh")) else n
                links.append(f"[{tag}]({n})")
            main = next((p for p in ps if p.endswith(".txt") and not p.endswith("_smoke.txt")), ps[0])
            rows.append([f"`{k}`", " · ".join(links), repo.describe(main),
                         max(repo.date(p) for p in ps)])
        out.append(f"\n### {label.get(h, h)} ({len(keys)} chains)\n\n"
                   + table(rows, ["Chain", "Files", "Note (from the file header)", "Last change"]))
    return "\n".join(out)


def record_scripts(repo, paths, k=2):
    c = Counter()
    for p in paths:
        m = re.search(r"^# command\s*:\s*(.+)$", repo.content(p)[:2000], re.M)
        if not m:
            continue
        for tok in m.group(1).split():
            if tok.startswith("scripts/dev/"):
                continue
            if re.search(r"\.(py|sh)$", tok):
                c[tok.rsplit("/", 1)[-1]] += 1
                break
            if re.match(r"^(tools|stages|scripts)/", tok):
                c[tok.rsplit("/", 1)[-1]] += 1
                break
    return ", ".join(f"`{n}`" for n, _ in c.most_common(k)) or "—"


def results_index(repo):
    files = [p for p in repo.files("results", True) if p != "results/README.md"]
    top = defaultdict(list)
    loose = []
    for p in files:
        rest = p[len("results/"):]
        (top[rest.split("/")[0]] if "/" in rest else loose).append(p)
    loose = [p for p in loose if not p.endswith("README.md")]
    out = [f"{len(files)} record files: {len(top)} subdirectories, plus {len(loose)} loose files at the top "
           "(early records from late September to early October). Each record header gives the command, the md5 of "
           "the inputs, the source commit, the host and the time. Main generators are the two script names that occur "
           "most often as the first script in the `# command` lines."]
    rows = []
    for name in sorted(top, key=lambda n: (-len(top[n]), n)):
        ps = top[name]
        lo = min(repo.first.get(p, repo.date(p)) for p in ps)
        hi = max(repo.date(p) for p in ps)
        rows.append([f"[`{name}/`]({name}/)", str(len(ps)), f"{lo} – {hi}", record_scripts(repo, ps)])
    out.append("\n### Subdirectories (by file count)\n\n" + table(rows, ["Directory", "Files", "Dates", "Main generators"]))
    rows = [[f"[`{p[8:]}`]({p[8:]})", repo.date(p), record_scripts(repo, [p], 1)]
            for p in sorted(loose, key=repo.date)]
    out.append(f"\n### Loose files at the top ({len(loose)})\n\n" + table(rows, ["File", "Date", "Generator"]))
    return "\n".join(out)


def notes_index(repo, d, kinds):
    files = [p for p in repo.files(d) if p.endswith(".md") and not p.endswith("README.md")]
    groups = defaultdict(list)
    for p in files:
        name = p.rsplit("/", 1)[1]
        k = next((label for label, rx in kinds if re.match(rx, name)), "Other")
        groups[k].append(p)
    out = [f"`{d}/` holds {len(files)} notes, grouped by file-name prefix, newest change first."]
    for k in [label for label, _ in kinds] + ["Other"]:
        ps = sorted(groups.get(k, []), key=lambda p: (repo.date(p), p), reverse=True)
        if not ps:
            continue
        rows = [[f"[`{p.rsplit('/', 1)[1]}`]({p.rsplit('/', 1)[1]})", repo.describe(p), repo.date(p)]
                for p in ps]
        out.append(f"\n### {k} ({len(ps)})\n\n" + table(rows, ["File", "Title", "Last change"]))
    subs = sorted({p[len(d) + 1:].split("/")[0] for p in repo.files(d, True) if "/" in p[len(d) + 1:]})
    if subs:
        rows = [[f"[`{s}/`]({s}/)", str(len(repo.files(f"{d}/{s}", True)))] for s in subs]
        out.append(f"\n### Subdirectories ({len(subs)})\n\n" + table(rows, ["Directory", "Files"]))
    return "\n".join(out)


def root_map(repo):
    top = Counter(p.split("/")[0] for p in repo.blobs if "/" in p)
    desc = {
        "results": "Command output records (board snapshots, exports, evaluations, operations); files are only added",
        "stages": "Code of the four pipeline stages: recovery, retarget, policy, evaluate",
        "agent-doc": "Plans, reviews, handoffs and experiment notes; not a source of facts",
        "tools": "Operations and archive tools: HF, leaderboard, site, remote queries",
        "docs": "Formal documents: handbook, ADRs, contracts, technical report, HF READMEs",
        "scripts": "Record wrapper (scripts/dev/record) and development helpers",
        "deploy": "Container images and the runtime of each host",
        "third_party": "Patches and sha256 of the FlashCHORD variants (official source unmodified)",
        "libs": "Shared layer v2d_infra: paths, tier isolation, metrics",
        "project-page": "Public project page (published from the gh-pages branch)",
    }
    rows = [[f"[`{d}/`]({d}/)", str(n), desc.get(d, "")] for d, n in top.most_common()]
    return f"{len(repo.blobs)} tracked files.\n\n" + table(rows, ["Directory", "Files", "Contents"])


def targets(repo):
    t = {"README.md": lambda: root_map(repo)}
    for d in ("stages/policy", "stages/evaluate", "stages/recovery", "stages/retarget",
              "tools", "scripts/dev", "libs/v2d_infra"):
        t[f"{d}/README.md"] = (lambda d=d: code_index(repo, d))
    t["stages/policy/queues/README.md"] = lambda: queues_index(repo, "stages/policy/queues")
    t["results/README.md"] = lambda: results_index(repo)
    t["agent-doc/README.md"] = lambda: notes_index(repo, "agent-doc", [
        ("Plans", r"^plan-"), ("Reviews", r"^review-"), ("Handoffs", r"^handoff-"), ("Decisions", r"^decision-"),
        ("Organizer correspondence", r"^organizer-"),
        ("Progress, strategy and freeze", r"^(progress|strategy|freeze|report|board|t3-recon)")])
    t["agent-doc/experiments/README.md"] = lambda: notes_index(repo, "agent-doc/experiments", [
        ("September", r"^2026-09"), ("October", r"^2026-10"), ("November", r"^2026-11")])
    return t


def splice(old, body):
    block = f"{BEGIN}\n\n{body}\n\n{END}"
    for ob, oe in OLD_MARKERS:
        old = old.replace(ob, BEGIN).replace(oe, END)
    if BEGIN in old and END in old:
        a = old.index(BEGIN)
        b = old.index(END) + len(END)
        return old[:a] + block + old[b:]
    return old.rstrip("\n") + "\n\n" + block + "\n"


def main():
    check = "--check" in sys.argv[1:]
    dump = "--dump-zh" in sys.argv[1:]
    repo = Repo()
    stale = []
    if dump:
        for gen in targets(repo).values():
            gen()
        for path in sorted(repo.missing):
            print(f"{path}\t{repo.missing[path]}")
        return 0
    for path, gen in targets(repo).items():
        f = Path(path)
        old = f.read_text("utf-8") if f.exists() else ""
        new = splice(old, gen())
        if new != old:
            stale.append(path)
            if not check:
                f.write_text(new, "utf-8")
    verb = "stale" if check else "updated"
    print(f"{verb} {len(stale)}: " + (", ".join(stale) if stale else "none"))
    if repo.missing:
        print(f"{len(repo.missing)} purposes without an English translation (run --dump-zh)")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
